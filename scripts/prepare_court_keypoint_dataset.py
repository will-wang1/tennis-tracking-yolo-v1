"""Convert the yastrebksv/TennisCourtDetector dataset into YOLO-pose format.

    python scripts/prepare_court_keypoint_dataset.py

Reads `data_train.json` / `data_val.json` (each a list of
`{"id": ..., "kps": [[x, y], ...]}` with exactly 14 keypoints per image) and
the `images/` directory from `data/raw_court_source/` (see
`scripts/download_court_dataset.py`), and writes
`data/raw_court/{train,valid}/{images,labels}` in YOLO-pose format, plus
`configs/court_keypoints_dataset.yaml` - matching the layout
`scripts/train_court_keypoints.py` and `configs/ball_dataset.yaml` already
use for the ball detector.

Each image has exactly one "court" instance. The bounding box is the tight
box around the 14 keypoints (the source dataset has no separate box
annotation) - reasonable since the keypoints already span the full court,
and the box only exists because YOLO's pose task attaches keypoints to a
detected box; the keypoint head is what this pipeline actually needs.
"""

import argparse
import json
import shutil
from pathlib import Path

import cv2
from tqdm import tqdm

REPO_ROOT = Path(__file__).resolve().parent.parent
NUM_KEYPOINTS = 14
# matches src.detection.court_keypoint_detector.COURT_KEYPOINT_FLIP_INDEX
FLIP_IDX = "1, 0, 3, 2, 6, 7, 4, 5, 9, 8, 11, 10, 12, 13"


def find_file(root: Path, name: str) -> Path:
    matches = list(root.rglob(name))
    if not matches:
        raise SystemExit(f"Could not find {name} under {root} - did scripts/download_court_dataset.py finish?")
    return matches[0]


def find_dir(root: Path, name: str) -> Path:
    matches = [p for p in root.rglob(name) if p.is_dir()]
    if not matches:
        raise SystemExit(f"Could not find a '{name}' directory under {root}")
    return matches[0]


def convert_split(entries: list[dict], images_dir: Path, out_dir: Path, box_margin: float = 0.03) -> int:
    images_out = out_dir / "images"
    labels_out = out_dir / "labels"
    images_out.mkdir(parents=True, exist_ok=True)
    labels_out.mkdir(parents=True, exist_ok=True)

    written = 0
    for entry in tqdm(entries):
        image_path = images_dir / f"{entry['id']}.png"
        if not image_path.exists():
            continue
        img = cv2.imread(str(image_path))
        if img is None:
            continue
        height, width = img.shape[:2]
        kps = entry["kps"]
        if len(kps) != NUM_KEYPOINTS:
            continue

        xs = [p[0] for p in kps]
        ys = [p[1] for p in kps]
        x_min, x_max = min(xs), max(xs)
        y_min, y_max = min(ys), max(ys)
        # pad the tight keypoint bbox a bit - YOLO's pose loss expects the
        # box to plausibly contain the object, not hug it to the pixel
        box_w = (x_max - x_min) * (1 + box_margin)
        box_h = (y_max - y_min) * (1 + box_margin)
        cx = (x_min + x_max) / 2
        cy = (y_min + y_max) / 2

        shutil.copy(image_path, images_out / image_path.name)

        parts = [
            "0",
            f"{cx / width:.6f}",
            f"{cy / height:.6f}",
            f"{box_w / width:.6f}",
            f"{box_h / height:.6f}",
        ]
        for x, y in kps:
            parts += [f"{x / width:.6f}", f"{y / height:.6f}", "2"]  # 2 = labeled + visible

        (labels_out / f"{entry['id']}.txt").write_text(" ".join(parts) + "\n")
        written += 1
    return written


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", default=str(REPO_ROOT / "data" / "raw_court_source"))
    parser.add_argument("--out", default=str(REPO_ROOT / "data" / "raw_court"))
    args = parser.parse_args()

    source = Path(args.source)
    images_dir = find_dir(source, "images")
    train_json = find_file(source, "data_train.json")
    val_json = find_file(source, "data_val.json")

    out = Path(args.out)
    train_entries = json.loads(train_json.read_text())
    val_entries = json.loads(val_json.read_text())

    print(f"{len(train_entries)} train, {len(val_entries)} val entries")
    n_train = convert_split(train_entries, images_dir, out / "train")
    n_val = convert_split(val_entries, images_dir, out / "valid")
    print(f"Wrote {n_train} train / {n_val} valid images+labels to {out}")

    yaml_path = REPO_ROOT / "configs" / "court_keypoints_dataset.yaml"
    yaml_path.write_text(
        "# YOLO-pose dataset config for the court-keypoint detector.\n"
        "# Generated by scripts/prepare_court_keypoint_dataset.py - see that\n"
        "# script and src/detection/court_keypoint_detector.py for the keypoint order.\n"
        f"path: {out}\n"
        "train: train/images\n"
        "val: valid/images\n"
        "\n"
        "nc: 1\n"
        'names: ["court"]\n'
        f"kpt_shape: [{NUM_KEYPOINTS}, 3]\n"
        f"flip_idx: [{FLIP_IDX}]\n"
    )
    print(f"Wrote {yaml_path}")


if __name__ == "__main__":
    main()
